#!/usr/bin/env node
// Letters (17 Nov 2026): turns the verified mailing list (CSV) into SQL that
// loads it into public.letter_recipients. For agents and for Jordan; the page's
// "Import mailing list" (op list_import) does the same thing with checks.
//
//   node --experimental-strip-types scripts/letters/seed_from_csv.mjs <list.csv> [out.sql] [list_version]
//
// The CSV has columns id,name,line1,line2,line3,line4,line5,postcode,town,
// unit_status,confidence (id = partners.id, or "proof" for Jordan's own
// address). Every row is checked with the same rules as the page (rules.ts);
// one bad row and nothing is written.
//
// The output holds business names and addresses, so it must never be written
// inside this repository (the repo is public): the script refuses any output
// path inside it. Default output: $LETTERS_SEED_OUT, else
// $SCRATCHPAD/letters-tool/seed_letters_addresses.sql.
//
// The SQL replaces the active list in one transaction (old rows are kept,
// inactive), inserts only rows whose studio exists, and aborts if the count
// does not match. Nothing is applied by this script.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..", "..");
const die = (msg, code = 1) => { console.error(msg); process.exit(code); };

const [csvArg, outArg, versionArg] = process.argv.slice(2);
if (!csvArg) die("Usage: node --experimental-strip-types scripts/letters/seed_from_csv.mjs <list.csv> [out.sql] [list_version]", 2);
const csvPath = path.resolve(csvArg);
if (!fs.existsSync(csvPath)) die(`CSV not found: regenerate the 15 Nov list first (${csvPath})`);

const scratch = process.env.SCRATCHPAD ? path.join(process.env.SCRATCHPAD, "letters-tool", "seed_letters_addresses.sql") : "";
const outPath = path.resolve(outArg || process.env.LETTERS_SEED_OUT || scratch || "");
if (!outArg && !process.env.LETTERS_SEED_OUT && !scratch) die("Say where to write the SQL (second argument, LETTERS_SEED_OUT or SCRATCHPAD). Never inside the repository.", 2);
const real = (p) => { try { return fs.realpathSync(p); } catch { return path.resolve(p); } };
const outDir = real(path.dirname(outPath));
const repoReal = real(repo);
if (outDir === repoReal || outDir.startsWith(repoReal + path.sep)) die(`Refusing to write ${outPath}: it is inside the repository, which is public. Write it to the scratchpad instead.`, 3);

let rules;
try {
  rules = await import(new URL("../../supabase/functions/letters/rules.ts", import.meta.url).href);
} catch (e) {
  die(`Could not load rules.ts (${e.message}). Run with: node --experimental-strip-types ${path.relative(process.cwd(), fileURLToPath(import.meta.url))} ...`, 2);
}

const listVersion = versionArg || "2026-11-15";
if (!/^[0-9A-Za-z._-]{1,40}$/.test(listVersion)) die("list_version: letters, digits, dots and dashes only.", 2);
const parsed = rules.parseListCsv(fs.readFileSync(csvPath, "utf8"));
if (!parsed.ok) {
  for (const e of parsed.errors) console.error(`  ${e.message}`);
  die(`${parsed.errors.length} problem(s) in ${csvPath}. Nothing was written.`);
}

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const studios = parsed.rows.filter((r) => r.kind === "studio");
const proofs = parsed.rows.filter((r) => r.kind === "proof");
const out = [];
out.push(`-- Letters mailing list ${listVersion}: ${studios.length} studios${proofs.length ? `, ${proofs.length} proof address(es)` : ""}.`);
out.push(`-- Generated by scripts/letters/seed_from_csv.mjs from ${path.basename(csvPath)} on ${new Date().toISOString()}.`);
out.push("-- Business names and addresses: keep this file out of the repository. Not applied by the script.");
out.push("begin;");
out.push("set local lock_timeout = '3s';");
out.push("update public.letter_recipients set active = false where active and kind = 'studio';");
if (proofs.length) out.push("update public.letter_recipients set active = false where active and kind = 'proof';");
for (const r of studios) {
  out.push(
    "insert into public.letter_recipients (kind, partner_id, list_version, display_name, greeting_name, address_lines, postcode, town, unit_status, confidence, partner_address_at_import, imported_by)\n" +
    `select 'studio', p.id, ${q(listVersion)}, ${q(r.address_lines[0])}, ${q(r.address_lines[0])}, ${arr(r.address_lines)}, ${q(r.postcode)}, ${q(r.town)}, ${q(r.unit_status)}, ${q(r.confidence)}, coalesce(p.address, ''), 'seed_from_csv'\n` +
    `  from public.partners p where p.id = ${q(r.partner_id)};`,
  );
}
for (const r of proofs) {
  out.push(
    "insert into public.letter_recipients (kind, partner_id, list_version, display_name, greeting_name, address_lines, postcode, town, unit_status, confidence, imported_by)\n" +
    `values ('proof', null, ${q(listVersion)}, ${q(r.address_lines[0])}, ${q(r.address_lines[0])}, ${arr(r.address_lines)}, ${q(r.postcode)}, ${q(r.town)}, ${q(r.unit_status)}, ${q(r.confidence)}, 'seed_from_csv');`,
  );
}
out.push(`do $$
begin
  if (select count(*) from public.letter_recipients where active and kind = 'studio' and list_version = ${q(listVersion)}) <> ${studios.length} then
    raise exception 'letters seed: expected ${studios.length} studios; some ids are not in partners. Nothing was changed.';
  end if;
end $$;`);
out.push("commit;");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out.join("\n") + "\n");
console.log(`Wrote ${studios.length} studios${proofs.length ? ` and ${proofs.length} proof address(es)` : ""} to ${outPath} (${parsed.warnings.length} warning(s)).`);
for (const w of parsed.warnings) console.log(`  warning: ${w.message}`);
