export function isSetupLang(v: unknown): v is SetupLang {
  return typeof v === "string" && (SETUP_LANGS as readonly string[]).includes(v);
}

/** Remembered choice for this browser, if any. */
export function loadSetupLang(): SetupLang | null {
  try {
    const v = localStorage.getItem(SETUP_LANG_STORAGE_KEY);
    return isSetupLang(v) ? v : null;
  } catch {
    return null;
  }
}

export function saveSetupLang(lang: SetupLang) {
  try {
    localStorage.setItem(SETUP_LANG_STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
}

/**
 * Default: the studio's saved preferred_language, else whatever this browser
 * chose before, else Spanish (most Madrid studio owners).
 */
export function resolveSetupLang(partnerPreferred?: unknown): SetupLang {
  if (isSetupLang(partnerPreferred)) return partnerPreferred;
  return loadSetupLang() ?? "es";
}

/** Translator for the setup flow. Falls back es -> en -> key. */
export function setupT(
  lang: SetupLang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const raw =
    SETUP_COPY[lang]?.[key] ?? SETUP_COPY.es[key] ?? SETUP_COPY.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{\{(\w+)\}\}/g, (m, name) =>
    name in vars ? String(vars[name]) : m,
  );
}

export type SetupT = (key: string, vars?: Record<string, string | number>) => string;

export function makeSetupT(lang: SetupLang): SetupT {
  return (key, vars) => setupT(lang, key, vars);
}
